import type { Metadata } from "next";
import { headers } from "next/headers";

import "react-loading-skeleton/dist/skeleton.css";
import "react-toastify/dist/ReactToastify.css";
import "./globals.css";

import React from "react";
import { SkeletonTheme } from "react-loading-skeleton";
import { ToastContainer } from "react-toastify";

import { InstallableContextProvider } from "@/contexts/InstallableContext";
import InstallPopUp from "@/components/InstallPopUp";
import { branding } from "@/edition/branding";

export const metadata: Metadata = {
  ...branding.metadata,
};

export default async function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  // Reading headers forces dynamic rendering for every route, ensuring
  // the per-request CSP nonce generated by middleware is applied to all
  // inline hydration scripts. Without this, statically rendered pages
  // would not carry nonces and would be blocked by 'strict-dynamic'.
  await headers();

  return (
    <html lang="pt" className="h-svh">
      <body>
        <a
          href="#main-content"
          className="sr-only z-50 bg-primary p-3 text-black focus:not-sr-only focus:fixed focus:top-2 focus:left-2"
        >
          Saltar para o conteúdo principal
        </a>
        <InstallableContextProvider>
          <SkeletonTheme baseColor="#eaeaea" highlightColor="#bfbfbf">
            {children}
            <ToastContainer
              position="bottom-right"
              theme="dark"
              autoClose={5000}
              newestOnTop
              closeOnClick
              pauseOnHover
              pauseOnFocusLoss
              draggable
              limit={4}
              className="fallstack-toasts"
            />
            <InstallPopUp />
          </SkeletonTheme>
        </InstallableContextProvider>
      </body>
    </html>
  );
}
